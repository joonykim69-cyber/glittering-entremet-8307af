// 주소 문자열 → 법정동코드 5자리. "경기도 수원시 권선구 금곡동" 같은 온비드 주소를 받는다.
// 시도명은 축약형(경기)·정식형(경기도)·특별자치 표기가 섞여 온다.
// 수원시 권선구처럼 **시 아래 구**가 있으면 "수원시 권선구"가 테이블 키다.
function lawdOf(region) {
  const t = String(region || '').trim().split(/\s+/).filter(Boolean);
  if (t.length < 2) return '';
  const raw = t[0];
  const head = (SIDO_ALIAS[raw] || raw).slice(0, 2);
  const sido = Object.keys(LAWD).find(k => k.slice(0, 2) === head);
  if (!sido) return '';
  const m = LAWD[sido];
  // 긴 키("수원시 권선구")를 먼저 시도하고 짧은 키로 물러난다.
  for (const n of [t.slice(1, 3).join(' '), t[1], t[2]]) if (n && m[n]) return m[n];
  // 세종처럼 시군구가 없는 단층 시도는 시도명 자체가 키다("세종특별자치시 조치원읍").
  if (m[raw]) return m[raw];
  const only = Object.values(m);
  if (only.length === 1 || new Set(only).size === 1) return only[0];
  return '';
}

module.exports = { LAWD, lawdOf };
